import InfoTooltip from '../../components/InfoTooltip';
import styles from '../../styles/SmartScheduling.module.css';

const getSeverityBorder = (severity) => {
    if (severity === 'High') return '4px solid #dc2626';
    if (severity === 'Medium') return '4px solid #d97706';
    return '4px solid #10b981';
};

const ActionRecommendations = ({ actions = [], loading }) => {
    return (
        <div className={styles.card}>
            <div className={styles.cardHeader}>
                <div style={{ display: 'flex', alignItems: 'center', gap: '6px' }}>
                    <h3 className={styles.cardTitle}>Action Recommendations</h3>
                    <InfoTooltip
                        title="Prescriptive Operational Alerts"
                        content="Rule-based operational alerts generated by evaluating request priority, estimated monetary value, age, and fleet capacity limits to prevent backlogs."
                        size={15}
                        position="bottom"
                        width={270}
                    />
                </div>
            </div>
            <span className={styles.cardSub}>Prescriptive actions generated from priority, value, age, and capacity signals</span>
            {loading ? (
                <p style={{ color: '#64748b', fontSize: '13px' }}>Loading recommendations...</p>
            ) : actions.length === 0 ? (
                <div style={{ padding: '24px', background: '#f8fafc', borderRadius: '8px', textAlign: 'center', color: '#64748b', fontSize: '13px', border: '1px dashed #cbd5e1' }}>
                    No pending action recommendations needed.
                </div>
            ) : (
                <div className={styles.actionList}>
                    {actions.map((action) => (
                        <div
                            key={action.type}
                            className={styles.actionItem}
                            style={{ borderLeft: getSeverityBorder(action.severity) }}
                        >
                            <div className={styles.actionItemHeader}>
                                <div className={styles.actionItemTitle}>{action.type}</div>
                                <span
                                    style={{
                                        padding: '2px 8px',
                                        borderRadius: '999px',
                                        backgroundColor: '#f1f5f9',
                                        color: '#334155',
                                        fontSize: '11px',
                                        fontWeight: 700,
                                        whiteSpace: 'nowrap'
                                    }}
                                >
                                    {action.metric}
                                </span>
                            </div>
                            <p className={styles.actionItemMsg}>{action.message}</p>
                        </div>
                    ))}
                </div>
            )}
        </div>
    );
};

export default ActionRecommendations;
